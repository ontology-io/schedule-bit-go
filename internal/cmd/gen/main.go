// Command gen regenerates api/api.gen.go from the SDKs' 3.1 contract
// (../spec/openapi.json in the monorepo).
//
// The Go generators read OpenAPI 3.0, so the contract is first written down
// as 3.0.3: a type list with "null" becomes nullable, a mixed type list
// becomes any, const becomes a one-member enum, and the 3.1-only keywords the
// SDK has no use for are dropped. Then oapi-codegen (pinned) writes the types
// and one method per operation.
//
//	go run ./internal/cmd/gen          # write
//	go run ./internal/cmd/gen -check   # fail when api/api.gen.go is stale
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// The generator version is pinned: the same spec always yields the same file.
const generator = "github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.0"

const (
	specPath = "../spec/openapi.json"
	outPath  = "api/api.gen.go"
)

func main() {
	check := flag.Bool("check", false, "fail when the generated file is stale")
	flag.Parse()

	raw, err := os.ReadFile(specPath)
	must(err)
	var doc map[string]any
	must(json.Unmarshal(raw, &doc))
	table := operations(doc)
	down := Downgrade(doc)

	tmp, err := os.MkdirTemp("", "sbgen")
	must(err)
	defer os.RemoveAll(tmp)
	spec30 := filepath.Join(tmp, "openapi.json")
	b, err := json.MarshalIndent(down, "", "  ")
	must(err)
	must(os.WriteFile(spec30, b, 0o600))

	cfg := filepath.Join(tmp, "cfg.yaml")
	must(os.WriteFile(cfg, []byte("package: api\ngenerate:\n  models: true\n  client: true\noutput-options:\n  skip-prune: true\n"), 0o600))

	out := filepath.Join(tmp, "api.gen.go")
	cmd := exec.Command("go", "run", generator, "-config", cfg, "-o", out, spec30)
	cmd.Stderr = os.Stderr
	must(cmd.Run())
	fresh, err := os.ReadFile(out)
	must(err)

	files := map[string][]byte{outPath: fresh, opsPath: table}
	if *check {
		for path, want := range files {
			old, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(old, want) {
				fmt.Fprintf(os.Stderr, "%s is stale: run `go run ./internal/cmd/gen` in sdks/go\n", path)
				os.Exit(1)
			}
		}
		fmt.Println("generated code is current")
		return
	}
	for path, b := range files {
		must(os.WriteFile(path, b, 0o644))
		fmt.Println("wrote", path)
	}
}

const opsPath = "api/operations.gen.go"

// operations writes the table the transport reads to decide, per request,
// whether it carries an Idempotency-Key (the spec declares the parameter) and
// whether it may be repeated after a network failure or a 5xx (reads,
// explainClaim, and keyed writes).
func operations(doc map[string]any) []byte {
	type op struct {
		id, method, path string
		keyed, repeatable bool
	}
	var ops []op
	paths, _ := doc["paths"].(map[string]any)
	for path, item := range paths {
		methods, _ := item.(map[string]any)
		shared, _ := methods["parameters"].([]any)
		for method, raw := range methods {
			o, ok := raw.(map[string]any)
			if !ok || method == "parameters" {
				continue
			}
			params, _ := o["parameters"].([]any)
			keyed := false
			for _, p := range append(append([]any{}, shared...), params...) {
				pm, _ := p.(map[string]any)
				if ref, _ := pm["$ref"].(string); ref == paramRef+"IdempotencyKey" || pm["name"] == "Idempotency-Key" {
					keyed = true
				}
			}
			id, _ := o["operationId"].(string)
			m := strings.ToUpper(method)
			ops = append(ops, op{id, m, path, keyed, keyed || m == "GET" || m == "HEAD" || id == "explainClaim"})
		}
	}
	sort.Slice(ops, func(i, j int) bool { return ops[i].id < ops[j].id })
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/cmd/gen from the contract. DO NOT EDIT.\n\npackage api\n\n")
	b.WriteString("// Operation is one operation of the contract, as the transport needs it.\ntype Operation struct {\n\tID, Method, Path string\n\t// Keyed: the operation declares Idempotency-Key, so the SDK sends one.\n\tKeyed bool\n\t// Repeatable: safe to send again after a network failure or a 5xx.\n\tRepeatable bool\n}\n\n")
	b.WriteString("// Operations lists every operation in the contract.\nvar Operations = []Operation{\n")
	for _, o := range ops {
		fmt.Fprintf(&b, "\t{ID: %q, Method: %q, Path: %q, Keyed: %t, Repeatable: %t},\n", o.id, o.method, o.path, o.keyed, o.repeatable)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// Downgrade rewrites a 3.1 document as 3.0.3, in place, and returns it.
func Downgrade(doc map[string]any) map[string]any {
	doc["openapi"] = "3.0.3"
	delete(doc, "webhooks")
	walk(doc)
	renameParameters(doc)
	return doc
}

// renameParameters suffixes shared parameters with "Param": a parameter and a
// schema may share a name in OpenAPI (World), but not a Go type name.
func renameParameters(doc map[string]any) {
	comps, _ := doc["components"].(map[string]any)
	params, _ := comps["parameters"].(map[string]any)
	if params == nil {
		return
	}
	renamed := map[string]any{}
	for k, v := range params {
		renamed[k+"Param"] = v
	}
	comps["parameters"] = renamed
	var fix func(any)
	fix = func(node any) {
		switch n := node.(type) {
		case []any:
			for _, v := range n {
				fix(v)
			}
		case map[string]any:
			if ref, ok := n["$ref"].(string); ok && len(ref) > len(paramRef) && ref[:len(paramRef)] == paramRef {
				n["$ref"] = ref + "Param"
			}
			for _, v := range n {
				fix(v)
			}
		}
	}
	fix(doc)
}

const paramRef = "#/components/parameters/"

var dropped = []string{"unevaluatedProperties", "examples", "contentMediaType", "contentEncoding", "$comment"}

func walk(node any) {
	switch n := node.(type) {
	case []any:
		for _, v := range n {
			walk(v)
		}
	case map[string]any:
		schema(n)
		keys := make([]string, 0, len(n))
		for k := range n {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			walk(n[k])
		}
	}
}

// schema applies the 3.1 → 3.0 rules to one object, if it is a schema.
func schema(n map[string]any) {
	if types, ok := n["type"].([]any); ok {
		var rest []string
		for _, t := range types {
			if t == "null" {
				n["nullable"] = true
			} else if s, ok := t.(string); ok {
				rest = append(rest, s)
			}
		}
		if len(rest) == 1 {
			n["type"] = rest[0]
		} else {
			delete(n, "type")
		}
	}
	if c, ok := n["const"]; ok {
		n["enum"] = []any{c}
		if _, typed := n["type"]; !typed {
			switch c.(type) {
			case string:
				n["type"] = "string"
			case bool:
				n["type"] = "boolean"
			case float64:
				n["type"] = "number"
			}
		}
		delete(n, "const")
	}
	if props, ok := n["properties"].(map[string]any); ok {
		for k, v := range props {
			switch b := v.(type) {
			case bool:
				if b {
					props[k] = map[string]any{}
				} else {
					delete(props, k)
				}
			}
		}
	}
	if items, ok := n["items"].(bool); ok {
		if items {
			n["items"] = map[string]any{}
		} else {
			delete(n, "items")
		}
	}
	for _, k := range dropped {
		if _, isSchemaWord := n[k]; isSchemaWord {
			// "examples" is also a media-type/parameter member in 3.0 (a map);
			// only the 3.1 schema form (a list) goes.
			if k == "examples" {
				if _, list := n[k].([]any); !list {
					continue
				}
			}
			delete(n, k)
		}
	}
}
